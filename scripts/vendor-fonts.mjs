// Copies the site's fonts from @fontsource packages into src/assets/fonts (woff2 only) and writes fonts.css.
// Fonts are served from the site itself, so pages load without Google Fonts or any other third party.
// Run after updating the @fontsource packages:  node scripts/vendor-fonts.mjs
import { readFileSync, writeFileSync, mkdirSync, copyFileSync, rmSync, existsSync } from "node:fs";
import { join } from "node:path";

const FAMILIES = [
  { pkg: "forum", css: ["400.css"] },
  { pkg: "gentium-book-plus", css: ["400.css", "400-italic.css", "700.css"] },
  { pkg: "alegreya-sans-sc", css: ["500.css", "700.css"] },
];
const OUT = "src/assets/fonts";

rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });
let css = "/* Generated by scripts/vendor-fonts.mjs from @fontsource packages (SIL Open Font License). */\n";
let files = 0;

for (const { pkg, css: sheets } of FAMILIES) {
  const src = join("node_modules/@fontsource", pkg);
  const dst = join(OUT, pkg);
  mkdirSync(dst, { recursive: true });
  for (const sheet of sheets) {
    const text = readFileSync(join(src, sheet), "utf8").replace(
      /url\(\.\/files\/([^)]+?)\.woff2\) format\('woff2'\), url\(\.\/files\/[^)]+?\.woff\) format\('woff'\)/g,
      (_, name) => {
        copyFileSync(join(src, "files", `${name}.woff2`), join(dst, `${name}.woff2`));
        files += 1;
        return `url(./${pkg}/${name}.woff2) format('woff2')`;
      },
    );
    css += `\n/* ${pkg} ${sheet} */\n${text}`;
  }
  for (const lic of ["LICENSE", "LICENSE.md", "OFL.txt"]) {
    if (existsSync(join(src, lic))) copyFileSync(join(src, lic), join(dst, "LICENSE.txt"));
  }
}
writeFileSync(join(OUT, "fonts.css"), css);
console.log(`fonts.css written, ${files} woff2 files copied to ${OUT}`);
